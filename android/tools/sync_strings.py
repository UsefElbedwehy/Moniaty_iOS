#!/usr/bin/env python3
"""Copies the iOS Localizable.strings files into Android string resources, so both apps show
identical text. Arabic goes to values/ (the default locale), English to values-en/.

Keys keep their iOS names with dots turned into underscores ("auth.phone.title" ->
auth_phone_title). Run from android/:  python3 tools/sync_strings.py
Edit text on iOS (the source of truth), then re-run this; don't edit the generated XML.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]          # repo root
ANDROID = ROOT / "android"

# iOS strings folder -> (Android module, resource-name prefix to avoid clashes, generate key map?)
MODULES = [
    ("Packages/DesignSystem/Sources/DesignSystem/Resources", "designsystem", "ds_", False),
    ("Packages/Shared/Sources/Shared/Resources", "shared", "shared_", False),
    ("Packages/Authentication/Sources/Authentication/Resources", "authentication", "", False),
    ("App/Localization", "app", "", True),
]

ENTRY = re.compile(r'^\s*"((?:[^"\\]|\\.)+)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)


def parse(path: Path) -> dict:
    text = re.sub(r"/\*.*?\*/", "", path.read_text(encoding="utf-8"), flags=re.S)
    out = {}
    for key, value in ENTRY.findall(text):
        out[key] = value.replace('\\"', '"').replace("\\n", "\n")   # last one wins, like iOS
    return out


def android_value(value: str) -> str:
    value = re.sub(r"%(\d+\$)?@", lambda m: "%" + (m.group(1) or "") + "s", value)
    count = len(re.findall(r"%(?!%)", value))
    value = (value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n"))
    if value.startswith(("@", "?")):
        value = "\\" + value
    return value, count


def write(res_dir: Path, entries: dict, prefix: str, header: str):
    res_dir.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {header} -->", "<resources>"]
    for key in sorted(entries):
        value, count = android_value(entries[key])
        attrs = ' formatted="false"' if count > 1 and "$" not in value else ""
        lines.append(f'    <string name="{prefix}{key.replace(".", "_")}"{attrs}>{value}</string>')
    lines.append("</resources>")
    (res_dir / "strings_ios.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    header = "Generated by tools/sync_strings.py from the iOS .strings files. Do not edit."
    for src, module, prefix, keymap in MODULES:
        ar = parse(ROOT / src / "ar.lproj/Localizable.strings")
        en = parse(ROOT / src / "en.lproj/Localizable.strings")
        res = ANDROID / module / "src/main/res"
        write(res / "values", {**en, **ar}, prefix, header)   # Arabic default; English fills gaps
        write(res / "values-en", en, prefix, header)
        if keymap:
            # Dashboard overrides (RemoteStrings) are keyed by the iOS key; map resource ids back.
            kt = ANDROID / module / "src/main/java/co/munyati/app/composition/L10nKeys.kt"
            body = "\n".join(f'    R.string.{k.replace(".", "_")} to "{k}",' for k in sorted(en))
            kt.parent.mkdir(parents=True, exist_ok=True)
            kt.write_text(
                f"// {header}\npackage co.munyati.app.composition\n\nimport co.munyati.app.R\n\n"
                "/** App string resource id -> the iOS/dashboard key used by `app_strings` overrides. */\n"
                f"internal val l10nKeys: Map<Int, String> = mapOf(\n{body}\n)\n",
                encoding="utf-8")
        print(f"{module}: {len(ar)} ar / {len(en)} en")


if __name__ == "__main__":
    main()
