#!/usr/bin/env python3
"""Converts the brand SVGs (plain filled paths, as exported for iOS) to Android vector drawables.
Usage: python3 tools/svg_to_vector.py <in.svg> <out.xml>"""
import re
import sys
import xml.etree.ElementTree as ET

src, dst = sys.argv[1], sys.argv[2]
root = ET.parse(src).getroot()
ns = {"s": "http://www.w3.org/2000/svg"}
min_x, min_y, w, h = (float(v) for v in root.get("viewBox").split())
size = 240  # intrinsic dp size; screens always set an explicit size
paths = []
for p in root.iter("{http://www.w3.org/2000/svg}path"):
    fill = p.get("fill", "#000000")
    paths.append(f'        <path android:fillColor="{fill}" android:pathData="{p.get("d").strip()}"/>')
out = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/svg_to_vector.py from {src.split("/")[-1]}. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size * h / w:.0f}dp"
    android:viewportWidth="{w}" android:viewportHeight="{h}"
    android:autoMirrored="false">
    <group android:translateX="{-min_x}" android:translateY="{-min_y}">
{chr(10).join(paths)}
    </group>
</vector>
'''
open(dst, "w").write(out)
print(dst, len(paths), "paths")
